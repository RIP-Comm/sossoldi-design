// Generates lib/catalog/widget_names.g.dart: the names of the public widgets
// of the app (design system components and feature screens).
//
// A release web build minifies type names, so `runtimeType.toString()` is
// useless there: the Inspector recognizes widgets with `is` checks instead.
// Run from inspector/ after adding or renaming a widget:
//   dart run tool/generate_widget_names.dart

import 'dart:io';

final _widgetClass = RegExp(
  r'^class ([A-Z]\w*)(?:<[^>]*>)? extends (?:StatelessWidget|StatefulWidget)\b',
  multiLine: true,
);

List<(String, String)> _scan(String dir) {
  final found = <(String, String)>[];
  final files =
      Directory('../lib/$dir')
          .listSync(recursive: true)
          .whereType<File>()
          .where((f) => f.path.endsWith('.dart') && !f.path.endsWith('.g.dart'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  for (final file in files) {
    final path = file.path.substring('../lib/'.length);
    for (final m in _widgetClass.allMatches(file.readAsStringSync())) {
      found.add((path, m.group(1)!));
    }
  }
  return found;
}

void _writeFunction(
  StringBuffer out,
  String name,
  List<(String, String)> classes,
) {
  out.writeln('String? $name(Widget widget) {');
  for (final (_, cls) in classes) {
    out.writeln("  if (widget is $cls) return '$cls';");
  }
  out.writeln('  return null;');
  out.writeln('}');
}

void main() {
  final components = _scan('design_system/components');
  final features = _scan('features')..addAll(_scan('app'));
  final imports = <String, List<String>>{};
  for (final (path, cls) in [...components, ...features]) {
    imports.putIfAbsent(path, () => []).add(cls);
  }

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_widget_names.dart. Do not edit.')
    ..writeln(
      '// ignore_for_file: directives_ordering, curly_braces_in_flow_control_structures',
    )
    ..writeln()
    ..writeln("import 'package:flutter/widgets.dart';");
  for (final e in imports.entries) {
    out.writeln(
      "import 'package:sossoldi/${e.key}' show ${e.value.join(', ')};",
    );
  }
  out
    ..writeln()
    ..writeln('/// The design system component [widget] is, or null.');
  _writeFunction(out, 'designSystemName', components);
  out
    ..writeln()
    ..writeln('/// The screen or feature widget [widget] is, or null.');
  _writeFunction(out, 'featureName', features);

  File('lib/catalog/widget_names.g.dart')
    ..createSync(recursive: true)
    ..writeAsStringSync(out.toString());
  stdout.writeln(
    '${components.length} components, ${features.length} feature widgets',
  );
}
