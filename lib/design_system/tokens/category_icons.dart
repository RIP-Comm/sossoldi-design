/// A section of the icon picker: [icon] is its tab.
class CategoryIconGroup {
  const CategoryIconGroup(this.id, this.icon, this.icons);

  final CategoryIconGroupId id;
  final IconData icon;
  final List<IconData> icons;
}

abstract final class CategoryIcons {
  /// The sections, in the order of the tabs.
  static const groups = <CategoryIconGroup>[
    CategoryIconGroup(
      CategoryIconGroupId.finance,
      PhosphorIconsRegular.bank,
      _finance,
    ),
    CategoryIconGroup(
      CategoryIconGroupId.commerce,
      PhosphorIconsRegular.shoppingCart,
      _commerce,
    ),
    CategoryIconGroup(
      CategoryIconGroupId.travel,
      PhosphorIconsRegular.airplane,
      _travel,
    ),
    CategoryIconGroup(
      CategoryIconGroupId.health,
      PhosphorIconsRegular.heartbeat,
      _health,
    ),
    CategoryIconGroup(
      CategoryIconGroupId.people,
      PhosphorIconsRegular.users,
      _people,
    ),
    CategoryIconGroup(
      CategoryIconGroupId.nature,
      PhosphorIconsRegular.tree,
      _nature,
    ),
    CategoryIconGroup(
      CategoryIconGroupId.games,
      PhosphorIconsRegular.gameController,
      _games,
    ),
    CategoryIconGroup(
      CategoryIconGroupId.media,
      PhosphorIconsRegular.musicNotes,
      _media,
    ),
    CategoryIconGroup(
      CategoryIconGroupId.office,
      PhosphorIconsRegular.briefcase,
      _office,
    ),
    CategoryIconGroup(
      CategoryIconGroupId.communication,
      PhosphorIconsRegular.chatCircle,
      _communication,
    ),
    CategoryIconGroup(
      CategoryIconGroupId.objects,
      PhosphorIconsRegular.lightbulb,
      _objects,
    ),
  ];

  /// Every icon of every section.
  static final all = <IconData>[for (final g in groups) ...g.icons];

  /// The section an icon is in, or null.
  static CategoryIconGroup? groupOf(IconData icon) {
    for (final g in groups) {
      if (g.icons.contains(icon)) return g;
    }
    return null;
  }
}

